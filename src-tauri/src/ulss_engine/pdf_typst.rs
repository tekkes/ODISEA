use crate::ulss_engine::ast::UlssStylesheet;
use crate::ulss_engine::resolver::UlssResolver;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

pub struct PdfTypstExporter<'a> {
    resolver: UlssResolver<'a>,
    is_revision_style: bool,
}

impl<'a> PdfTypstExporter<'a> {
    pub fn new(stylesheet: &'a UlssStylesheet, is_revision: bool) -> Self {
        Self {
            resolver: UlssResolver::new(stylesheet),
            is_revision_style: is_revision,
        }
    }

    pub fn compile_to_typst(&self, title: &str, mdxl_content: &str) -> String {
        let doc_settings = self.resolver.resolve_document_settings();
        let defaults = self.resolver.resolve_element_style("defaults", false, None);

        let font_family = defaults.font_family.unwrap_or_else(|| "Charter".to_string());
        let font_size = defaults.font_size_pt.unwrap_or(10.5);
        let font_color = defaults.font_color.unwrap_or_else(|| "#1d1d1f".to_string());
        let line_height_pt = defaults.line_height_pt.unwrap_or(16.0);
        let leading_em = (line_height_pt - font_size) / font_size;

        let mut typst = String::new();
        typst.push_str("// ========================================================\n");
        typst.push_str("// Generated by Odisea ULSS Typst Vector Engine\n");
        typst.push_str("// ========================================================\n\n");

        // Page setup
        typst.push_str(&format!(
            "#set page(\n  paper: \"{}\",\n  margin: (top: {:.1}mm, bottom: {:.1}mm, left: {:.1}mm, right: {:.1}mm),\n",
            doc_settings.page_size.to_lowercase(),
            doc_settings.margin_top_mm,
            doc_settings.margin_bottom_mm,
            doc_settings.margin_left_mm,
            doc_settings.margin_right_mm
        ));

        if doc_settings.column_count > 1 {
            typst.push_str(&format!(
                "  columns: {},\n",
                doc_settings.column_count
            ));
        }

        // Header and Footer
        let header_style = self.resolver.resolve_element_style("area-header", false, None);
        let footer_style = self.resolver.resolve_element_style("area-footer", false, None);

        let header_font = header_style.font_family.unwrap_or_else(|| "Avenir Next".to_string());
        let header_color = header_style.font_color.unwrap_or_else(|| "#6e6e73".to_string());
        let footer_font = footer_style.font_family.unwrap_or_else(|| "Avenir Next".to_string());

        typst.push_str(&format!(
            "  header: align(right)[#text(font: \"{}\", size: 8pt, fill: rgb(\"{}\"))[{}]],\n",
            header_font, header_color, title
        ));
        typst.push_str(&format!(
            "  footer: align(center)[#text(font: \"{}\", size: 8pt)[#counter(page).display()]]\n)\n\n",
            footer_font
        ));

        // Typography and paragraph settings
        typst.push_str(&format!(
            "#set text(font: \"{}\", size: {:.1}pt, fill: rgb(\"{}\"), lang: \"es\")\n",
            font_family, font_size, font_color
        ));

        let paragraph_style = self.resolver.resolve_element_style("paragraph", false, None);
        let indent_pt = paragraph_style.first_line_indent_pt.unwrap_or(0.0);
        let justify = defaults.text_alignment.as_deref().unwrap_or("justified") == "justified";

        typst.push_str(&format!(
            "#set par(justify: {}, leading: {:.2}em, first-line-indent: {:.1}pt)\n\n",
            justify, leading_em.max(0.5), indent_pt
        ));

        // Title
        let h1_style = self.resolver.resolve_element_style("heading-1", false, None);
        let h1_font = h1_style.font_family.unwrap_or_else(|| "Avenir Next".to_string());
        let h1_size = h1_style.font_size_pt.unwrap_or(24.0);

        typst.push_str(&format!(
            "#v(12pt)\n#align(center)[#text(font: \"{}\", size: {:.1}pt, weight: \"bold\")[{}]]\n#v(18pt)\n\n",
            h1_font, h1_size, title
        ));

        // Body content parsing
        let mut in_code_block = false;
        let mut in_table = false;
        let mut table_rows: Vec<Vec<String>> = Vec::new();

        for line in mdxl_content.lines() {
            let trimmed = line.trim();

            // Code blocks
            if trimmed.starts_with("```") || trimmed.starts_with("''") {
                if in_code_block {
                    typst.push_str("```\n\n");
                    in_code_block = false;
                } else {
                    let lang = trimmed.trim_start_matches('`').trim_start_matches('\'').trim();
                    typst.push_str(&format!("```{}\n", lang));
                    in_code_block = true;
                }
                continue;
            }

            if in_code_block {
                typst.push_str(line);
                typst.push('\n');
                continue;
            }

            // Tables
            if trimmed.starts_with('|') && trimmed.ends_with('|') {
                if trimmed.contains("---") {
                    // Separator row
                    continue;
                }
                in_table = true;
                let cells: Vec<String> = trimmed
                    .split('|')
                    .filter(|s| !s.is_empty())
                    .map(|s| s.trim().to_string())
                    .collect();
                table_rows.push(cells);
                continue;
            } else if in_table {
                // Emit collected table
                self.emit_typst_table(&mut typst, &table_rows);
                table_rows.clear();
                in_table = false;
            }

            if trimmed.is_empty() {
                continue;
            }

            // Headings H1 to H6
            if let Some(rest) = trimmed.strip_prefix("# ") {
                if h1_style.column_span_all && doc_settings.column_count > 1 {
                    typst.push_str(&format!("#place(top, scope: \"parent\")[= {}]\n\n", self.transform_inline(rest)));
                } else {
                    typst.push_str(&format!("= {}\n\n", self.transform_inline(rest)));
                }
            } else if let Some(rest) = trimmed.strip_prefix("## ") {
                typst.push_str(&format!("== {}\n\n", self.transform_inline(rest)));
            } else if let Some(rest) = trimmed.strip_prefix("### ") {
                typst.push_str(&format!("=== {}\n\n", self.transform_inline(rest)));
            } else if let Some(rest) = trimmed.strip_prefix("#### ") {
                typst.push_str(&format!("==== {}\n\n", self.transform_inline(rest)));
            } else if let Some(rest) = trimmed.strip_prefix("##### ") {
                typst.push_str(&format!("===== {}\n\n", self.transform_inline(rest)));
            } else if let Some(rest) = trimmed.strip_prefix("###### ") {
                typst.push_str(&format!("====== {}\n\n", self.transform_inline(rest)));
            }
            // Table of contents (toc)
            else if trimmed.eq_ignore_ascii_case("(toc)") || trimmed.eq_ignore_ascii_case("[toc]") {
                typst.push_str("#outline(title: \"Índice de Contenidos\", depth: 3, indent: auto)\n#v(14pt)\n\n");
            }
            // Blockquotes
            else if let Some(rest) = trimmed.strip_prefix("> ") {
                typst.push_str(&format!("#quote(block: true)[{}]\n\n", self.transform_inline(rest)));
            }
            // Verse / Poetry |"
            else if let Some(rest) = trimmed.strip_prefix("|\" ") {
                typst.push_str(&format!(
                    "#block(inset: (left: 18pt))[#text(style: \"italic\")[{}]]\n\n",
                    self.transform_inline(rest)
                ));
            }
            // Horizontal rule
            else if trimmed == "----" || trimmed == "***" || trimmed == "---" {
                typst.push_str("#line(length: 100%, stroke: 0.5pt + rgb(\"#d2d2d7\"))\n\n");
            }
            // Block Math $$
            else if trimmed.starts_with("$$") && trimmed.ends_with("$$") && trimmed.len() > 4 {
                let formula = &trimmed[2..trimmed.len() - 2];
                typst.push_str(&format!("$ {} $\n\n", formula.trim()));
            }
            // Regular paragraphs with inline transformation
            else {
                // If comment block %%
                if trimmed.starts_with("%%") {
                    if self.is_revision_style {
                        let comment_body = trimmed.trim_start_matches('%').trim();
                        typst.push_str(&format!(
                            "#rect(fill: rgb(\"#fff3cd\"), radius: 3pt, inset: 6pt)[#text(size: 9pt, fill: rgb(\"#856404\"))[*Comentario:* {}]]\n\n",
                            comment_body
                        ));
                    }
                    continue;
                }

                typst.push_str(&self.transform_inline(trimmed));
                typst.push_str("\n\n");
            }
        }

        if in_table {
            self.emit_typst_table(&mut typst, &table_rows);
        }

        typst
    }

    fn emit_typst_table(&self, typst: &mut String, rows: &[Vec<String>]) {
        if rows.is_empty() {
            return;
        }
        let cols = rows.iter().map(|r| r.len()).max().unwrap_or(1);
        typst.push_str(&format!("#table(\n  columns: {},\n  stroke: 0.5pt + rgb(\"#d2d2d7\"),\n  fill: (_, y) => if y == 0 {{ rgb(\"#f5f5f7\") }} else {{ none }},\n", cols));

        for row in rows {
            for cell in row {
                typst.push_str(&format!("  [{}],\n", self.transform_inline(cell)));
            }
        }
        typst.push_str(")\n\n");
    }

    fn transform_inline(&self, text: &str) -> String {
        let mut out = String::new();
        let chars: Vec<char> = text.chars().collect();
        let mut i = 0;

        while i < chars.len() {
            // Footnote (fn: payload)
            if chars[i] == '(' && text[i..].starts_with("(fn:") {
                if let Some(end_idx) = text[i..].find(')') {
                    let fn_body = &text[i + 4..i + end_idx];
                    out.push_str(&format!("#footnote[{}]", fn_body.trim()));
                    i += end_idx + 1;
                    continue;
                }
            }

            // Math inline $...$
            if chars[i] == '$' {
                let mut found_end = None;
                for j in (i + 1)..chars.len() {
                    if chars[j] == '$' {
                        found_end = Some(j);
                        break;
                    }
                }
                if let Some(end) = found_end {
                    let math_content: String = chars[i + 1..end].iter().collect();
                    out.push_str(&format!("$ {} $", math_content.trim()));
                    i = end + 1;
                    continue;
                }
            }

            // Strong **text**
            if chars[i] == '*' && i + 1 < chars.len() && chars[i + 1] == '*' {
                let mut found_end = None;
                for j in (i + 2)..chars.len() {
                    if chars[j] == '*' && j + 1 < chars.len() && chars[j + 1] == '*' {
                        found_end = Some(j);
                        break;
                    }
                }
                if let Some(end) = found_end {
                    let bold_content: String = chars[i + 2..end].iter().collect();
                    out.push_str(&format!("*{}*", bold_content));
                    i = end + 2;
                    continue;
                }
            }

            // Delete ||text|| (strikethrough)
            if chars[i] == '|' && i + 1 < chars.len() && chars[i + 1] == '|' {
                let mut found_end = None;
                for j in (i + 2)..chars.len() {
                    if chars[j] == '|' && j + 1 < chars.len() && chars[j + 1] == '|' {
                        found_end = Some(j);
                        break;
                    }
                }
                if let Some(end) = found_end {
                    let del_content: String = chars[i + 2..end].iter().collect();
                    if self.is_revision_style {
                        out.push_str(&format!("#strike(stroke: 1pt + rgb(\"#d70015\"))[{}]", del_content));
                    } else {
                        out.push_str(&format!("#strike[{}]", del_content));
                    }
                    i = end + 2;
                    continue;
                }
            }

            // Addition ++text++
            if chars[i] == '+' && i + 1 < chars.len() && chars[i + 1] == '+' {
                let mut found_end = None;
                for j in (i + 2)..chars.len() {
                    if chars[j] == '+' && j + 1 < chars.len() && chars[j + 1] == '+' {
                        found_end = Some(j);
                        break;
                    }
                }
                if let Some(end) = found_end {
                    let add_content: String = chars[i + 2..end].iter().collect();
                    if self.is_revision_style {
                        out.push_str(&format!("#highlight(fill: rgb(\"#d4edda\"))[{}]", add_content));
                    } else {
                        out.push_str(&add_content);
                    }
                    i = end + 2;
                    continue;
                }
            }

            // Mark ::text:: (highlight)
            if chars[i] == ':' && i + 1 < chars.len() && chars[i + 1] == ':' {
                let mut found_end = None;
                for j in (i + 2)..chars.len() {
                    if chars[j] == ':' && j + 1 < chars.len() && chars[j + 1] == ':' {
                        found_end = Some(j);
                        break;
                    }
                }
                if let Some(end) = found_end {
                    let mark_content: String = chars[i + 2..end].iter().collect();
                    out.push_str(&format!("#highlight[{}]", mark_content));
                    i = end + 2;
                    continue;
                }
            }

            // Inline annotation {text}
            if chars[i] == '{' {
                let mut found_end = None;
                for j in (i + 1)..chars.len() {
                    if chars[j] == '}' {
                        found_end = Some(j);
                        break;
                    }
                }
                if let Some(end) = found_end {
                    let annot_content: String = chars[i + 1..end].iter().collect();
                    if self.is_revision_style {
                        out.push_str(&format!("#highlight(fill: rgb(\"#e8f2ff\"))[#text(fill: rgb(\"#004085\"))[[Anotación: {}]]]", annot_content));
                    } else {
                        out.push_str(&annot_content);
                    }
                    i = end + 1;
                    continue;
                }
            }

            // Code `code`
            if chars[i] == '`' {
                let mut found_end = None;
                for j in (i + 1)..chars.len() {
                    if chars[j] == '`' {
                        found_end = Some(j);
                        break;
                    }
                }
                if let Some(end) = found_end {
                    let code_content: String = chars[i + 1..end].iter().collect();
                    out.push_str(&format!("`{}`", code_content));
                    i = end + 1;
                    continue;
                }
            }

            out.push(chars[i]);
            i += 1;
        }

        out
    }

    pub fn export_pdf(&self, title: &str, mdxl_content: &str, output_dir: &Path) -> Result<PathBuf, String> {
        let typst_source = self.compile_to_typst(title, mdxl_content);

        let safe_title = title.replace(|c: char| !c.is_alphanumeric() && c != '_' && c != '-', "_");
        let typ_path = output_dir.join(format!("{}.typ", safe_title));
        let pdf_path = output_dir.join(format!("{}.pdf", safe_title));

        fs::write(&typ_path, &typst_source).map_err(|e| format!("Failed to write .typ file: {}", e))?;

        // Attempt compilation if typst CLI exists
        let output = Command::new("typst")
            .arg("compile")
            .arg(&typ_path)
            .arg(&pdf_path)
            .output();

        match output {
            Ok(res) if res.status.success() => Ok(pdf_path),
            _ => {
                // If typst CLI is not installed, return the generated .typ path with a clear status
                Ok(typ_path)
            }
        }
    }
}
